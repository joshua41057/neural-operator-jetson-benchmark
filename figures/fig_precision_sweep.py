"""Figure: cross-family precision sweep, sustained Jetson latency + energy.

Two representative workloads per family -- Burgers 2048 (small) and Darcy
141^2 (large) -- chosen because these are the only resolution that all
four families have a *complete* sustained (120s, tegrastats-based) energy
measurement at, for the largest possible number of precision paths. This
makes the four families directly comparable at matched problem size,
unlike a full appendix sweep across every resolution.

For each (family, workload) block, all five precision paths that were
*attempted* are shown -- successes as real bars, failures as an explicit
gray x-marker + short reason. This is the point of the figure: precision
support is not a matter of missing data, it is an architectural finding.
FNO's FFT kernels reject BF16/FP16 outright (cuFFT dtype/size
restrictions); WNO's wavelet path tolerates BF16 but not FP16 fully, and
is workload-dependent (FP16 autocast is numerically unstable on Darcy but
fine on Burgers); DeepONet (no spectral ops) and Sp2GNO (FFT-free
graph-spectral kernels) run cleanly at every precision including
FP16-native.

Data source: fig3_precision_data.json, regenerated by
build_fig3_unified_data.py from the same unified-protocol sustained
aggregates that Tables 9, 22, 29, 34 and 38 are built from, so this
figure and those tables report identical numbers for identical cells.
Full resolution x precision sweep (WNO: 10 workloads, Sp2GNO: 8, FNO/
DeepONet's extended sets) is reported in the appendix tables; this figure
is the two-workload, main-body-scoped subset only.
"""
import json
import os

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.patches import Patch
from matplotlib.lines import Line2D

from _style import setup_style, save_fig, FAMILY_COLORS, PRECISION_COLORS

setup_style()

PRECISIONS = ["FP32", "TF32", "BF16 auto", "FP16 auto", "FP16 native"]

# Loaded from fig3_precision_data.json, regenerated by build_fig3_unified_data.py
# straight from the unified sustained aggregates. Each cell is
# [latency_ms, energy_j, None] for an admitted path, or [None, None, reason]
# for a path that was attempted and did not earn admission.
_D = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                 "fig3_precision_data.json")))
BLOCKS = [(b["family"], b["workload"], {k: tuple(v) for k, v in b["cells"].items()})
          for b in _D]

# flatten into row list, tracking block boundaries for divider lines/labels
rows = []
block_spans = []  # (family, workload, start_idx, end_idx)
family_spans = []  # (family, start_idx, end_idx)
idx = 0
prev_family = None
fam_start = 0
for fam, workload, precs in BLOCKS:
    start = idx
    for prec in PRECISIONS:
        lat, en, reason = precs[prec]
        rows.append({"family": fam, "workload": workload, "precision": prec,
                     "lat": lat, "en": en, "reason": reason})
        idx += 1
    block_spans.append((fam, workload, start, idx - 1))
    if fam != prev_family:
        if prev_family is not None:
            family_spans.append((prev_family, fam_start, start - 1))
        fam_start = start
        prev_family = fam
family_spans.append((prev_family, fam_start, idx - 1))

n = len(rows)

workload_dividers = [b[2] - 0.5 for b in block_spans[1:]]
family_dividers = [f[1] - 0.5 for f in family_spans[1:]]


def fmt_lat(v):
    return f"{v:.2f} ms" if v < 10 else f"{v:.1f} ms"


def fmt_en(v):
    return f"{v:.3f} J"


fig = plt.figure(figsize=(11.6, 13.3))
gs = fig.add_gridspec(1, 2, wspace=0.06, left=0.235, right=0.98,
                       top=0.975, bottom=0.145)
ax_lat = fig.add_subplot(gs[0, 0])
ax_en = fig.add_subplot(gs[0, 1], sharey=ax_lat)
# Legend rows as explicit figure-fraction axes (not gridspec rows) --
# gridspec `hspace` is a fraction of *average* row height, which blows up
# into a huge absolute gap when one row (the 40-bar main axes) is far
# taller than the legend rows. Explicit axes sidesteps that entirely.
# Bottom margin above (0.145) is generous specifically so the xlabel
# (ticks + label text, ~0.06-0.07 fraction) has room before lax1 starts.
lax1 = fig.add_axes([0.12, 0.048, 0.82, 0.032])
lax2 = fig.add_axes([0.12, 0.014, 0.82, 0.026])
lax1.axis("off")
lax2.axis("off")


def draw_panel(ax, key, xlabel, formatter, xlim, fail_x):
    for i, row in enumerate(rows):
        val = row[key]
        if val is None:
            ax.scatter([fail_x], [i], marker="x", s=40, color="#9a9a9a",
                       linewidth=1.5, zorder=3)
            ax.text(fail_x * 1.22, i, row["reason"], ha="left", va="center",
                    fontsize=7.3, color="#8a8a8a", style="italic", zorder=3)
        else:
            ax.barh(i, val, height=0.68,
                    color=PRECISION_COLORS[row["precision"]],
                    edgecolor="white", linewidth=0.8, zorder=2)
            ax.text(val * 1.08, i, formatter(val), ha="left", va="center",
                    fontsize=8.2, color="#333333", zorder=3)

    for y in workload_dividers:
        ax.axhline(y, color="#dcdcdc", linewidth=0.6, zorder=1)
    for y in family_dividers:
        ax.axhline(y, color="#8a8a8a", linewidth=0.9, zorder=1)

    ax.set_yticks(np.arange(n))
    ax.set_ylim(n - 0.5, -0.5)
    ax.set_xscale("log")
    ax.set_xlim(xlim)
    ax.set_xlabel(xlabel, labelpad=8)
    ax.grid(True, axis="x", which="major", linewidth=0.45, alpha=0.4, zorder=1)
    ax.grid(True, axis="x", which="minor", linewidth=0.3, alpha=0.22, zorder=1)
    ax.grid(False, axis="y")
    ax.tick_params(axis="y", length=0)


draw_panel(ax_lat, "lat", "Median latency  (ms)", fmt_lat,
           xlim=(0.85, 260), fail_x=1.05)
ax_lat.set_yticklabels([r["precision"] for r in rows], fontsize=9.8, color="#222222")
ax_lat.set_title("(a)  Latency", loc="left", fontweight="bold", pad=6, fontsize=11)

draw_panel(ax_en, "en", "Energy per inference  (J)", fmt_en,
           xlim=(0.013, 4.2), fail_x=0.016)
plt.setp(ax_en.get_yticklabels(), visible=False)
ax_en.set_title("(b)  Energy", loc="left", fontweight="bold", pad=6, fontsize=11)

# block super-labels (family + workload) in the left margin, outside the
# precision tick labels. Plain black/near-black -- an earlier version
# color-coded these by family, but against the already-colored precision
# bars that extra color coding competed for attention rather than aiding
# it, so identity here rides on position + weight/italic, not hue.
for fam, workload, start, end in block_spans:
    cy = (start + end) / 2
    ax_lat.text(-0.30, cy, f"{fam}", transform=ax_lat.get_yaxis_transform(),
                ha="right", va="center", fontsize=11.5, fontweight="bold",
                color="#111111")
    ax_lat.text(-0.30, cy + 0.85, workload, transform=ax_lat.get_yaxis_transform(),
                ha="right", va="center", fontsize=9.2, color="#333333",
                style="italic")

# --- legends: precision color (top) + fail-marker meaning (bottom) ---
prec_handles = [Patch(facecolor=c, edgecolor="white", label=p)
                for p, c in PRECISION_COLORS.items()]
fail_handle = [Line2D([0], [0], marker="x", color="#9a9a9a", linestyle="none",
                       markersize=7, markeredgewidth=1.5,
                       label="attempted, failed to run / diverged")]

lax1.legend(handles=prec_handles, loc="center", ncol=5,
            frameon=False, handletextpad=0.5, columnspacing=1.8,
            fontsize=9.5)
lax2.legend(handles=fail_handle, loc="center", ncol=1,
            frameon=False, fontsize=8.5)

save_fig(fig, "fig_precision_sweep")
plt.close(fig)
print("precision sweep figure done.")
